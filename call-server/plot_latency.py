"""Latency Chart & Metrics Analysis Script.

Reads metrics.csv generated by the Call Server and plots:
1. End-to-end latency (e2e_ms) over time with rolling average.
2. Pipeline stage latency breakdown (ASR, MT, TTS).
3. Distribution of latencies comparing Audio Mode vs Subtitle Mode.

Usage:
    python plot_latency.py [path/to/metrics.csv]
"""

import sys
import csv
from pathlib import Path

def parse_metrics(csv_path: Path):
    if not csv_path.exists():
        print(f"Metrics file not found: {csv_path}")
        return []

    records = []
    with open(csv_path, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            try:
                records.append({
                    "ts_ms": int(row.get("ts_ms", 0)),
                    "room_id": row.get("room_id", ""),
                    "chunk_id": row.get("chunk_id", ""),
                    "lane": row.get("lane", "main"),
                    "mode": row.get("mode", "subtitle"),
                    "n_listeners": int(row.get("n_listeners", 0)),
                    "chunk_ms": int(row.get("chunk_ms", 0)),
                    "asr_ms": float(row.get("asr_ms", 0)),
                    "mt_ms": float(row.get("mt_ms", 0)),
                    "tts_ms": float(row.get("tts_ms", 0)),
                    "speech_total_ms": float(row.get("speech_total_ms", 0)),
                    "e2e_ms": float(row.get("e2e_ms", 0)),
                    "network_state": row.get("network_state", ""),
                })
            except (ValueError, TypeError):
                continue
    return records


def print_summary(records):
    if not records:
        print("No valid metric records found to summarize.")
        return

    n = len(records)
    e2e_vals = sorted(r["e2e_ms"] for r in records)
    asr_vals = [r["asr_ms"] for r in records]
    mt_vals = [r["mt_ms"] for r in records]
    tts_vals = [r["tts_ms"] for r in records]

    def percentile(arr, p):
        idx = int(len(arr) * p)
        return arr[min(idx, len(arr) - 1)]

    print("=" * 55)
    print("         MULTILINGUAL-MEET LATENCY BENCHMARK        ")
    print("=" * 55)
    print(f"Total Chunks Processed : {n}")
    print(f"End-to-End Latency     : Avg={sum(e2e_vals)/n:.1f}ms | P50={percentile(e2e_vals, 0.50):.1f}ms | P90={percentile(e2e_vals, 0.90):.1f}ms | P99={percentile(e2e_vals, 0.99):.1f}ms")
    print(f"  - ASR (Whisper)      : Avg={sum(asr_vals)/n:.1f}ms")
    print(f"  - MT (IndicTrans2)   : Avg={sum(mt_vals)/n:.1f}ms")
    print(f"  - TTS (Speech Synt)  : Avg={sum(tts_vals)/n:.1f}ms")
    print("=" * 55)


def plot_charts(records, output_img: Path):
    if not records:
        return

    try:
        import matplotlib.pyplot as plt
    except ImportError:
        print("matplotlib not installed. Run 'pip install matplotlib' to generate charts.")
        return

    indices = list(range(1, len(records) + 1))
    e2e = [r["e2e_ms"] for r in records]
    asr = [r["asr_ms"] for r in records]
    mt = [r["mt_ms"] for r in records]
    tts = [r["tts_ms"] for r in records]

    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(10, 8), sharex=True)

    # Subplot 1: Total End-to-End Latency
    ax1.plot(indices, e2e, color="#2563eb", marker="o", markersize=3, label="Total End-to-End (e2e_ms)")
    ax1.axhline(sum(e2e)/len(e2e), color="#ef4444", linestyle="--", label=f"Mean E2E ({sum(e2e)/len(e2e):.0f}ms)")
    ax1.set_title("End-to-End Translation & Dispatch Latency per Chunk", fontsize=12, fontweight="bold")
    ax1.set_ylabel("Latency (ms)")
    ax1.grid(True, linestyle=":", alpha=0.6)
    ax1.legend(loc="upper right")

    # Subplot 2: Pipeline Stage Breakdown (Stacked Bar)
    ax2.bar(indices, asr, label="ASR (Whisper)", color="#3b82f6", width=0.6)
    ax2.bar(indices, mt, bottom=asr, label="MT (IndicTrans2)", color="#10b981", width=0.6)
    bottom_tts = [a + m for a, m in zip(asr, mt)]
    ax2.bar(indices, tts, bottom=bottom_tts, label="TTS (Synthesis)", color="#f59e0b", width=0.6)
    ax2.set_title("Speech Translation Pipeline Latency Breakdown", fontsize=12, fontweight="bold")
    ax2.set_xlabel("Chunk Index")
    ax2.set_ylabel("Stage Time (ms)")
    ax2.grid(True, linestyle=":", alpha=0.6)
    ax2.legend(loc="upper right")

    plt.tight_layout()
    plt.savefig(output_img, dpi=200)
    print(f"Chart saved to: {output_img.resolve()}")


def main():
    default_csv = Path(__file__).resolve().parent / "metrics.csv"
    csv_path = Path(sys.argv[1]) if len(sys.argv) > 1 else default_csv
    output_png = csv_path.parent / "latency_report.png"

    records = parse_metrics(csv_path)
    print_summary(records)
    plot_charts(records, output_png)


if __name__ == "__main__":
    main()
